public class MethodsExercise1 {
    public static void main(String[] args) {
        showAge(20);
        doubleNumber(30);
    }

    public static void showAge(int age) {
        System.out.println("Your age is " + age);
    }

    public static void doubleNumber(double number) {
        double douNumber = number; 
        System.out.println("Double number: " + douNumber);
    }
}
