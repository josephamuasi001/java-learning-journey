public class WhileLoopExercise {
    public static void main(String[] args) {
        int number = 1;

        while (number <= 10) {
            System.out.println("Number: " + number);
            number++;
        }

        int number2 = 10;
        
        while (number2 >= 1) {
            System.out.println("Number: " + number2);
            number2--;
        }
    }
}
